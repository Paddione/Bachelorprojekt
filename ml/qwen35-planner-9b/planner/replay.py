"""U5: replay of the base model's own answers to keep non-think, think and vision intact.

Only prompts are taken from public datasets; every target is generated by the base
model itself, so the tuned model is pulled back toward its original behaviour.
"""
from __future__ import annotations

import argparse
import itertools
import json
import threading
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

from planner.common import DATA, append_jsonl, make_sample, read_jsonl, text_hash
from planner.llm import chat

# split name -> think mode used for the replay answer
TEXT_SOURCES = {
    "OpenThoughts3_1.2M_think": True,
    "smoltalk_multilingual8_Qwen3_32B_think": True,
    "smoltalk_everyday_convs_reasoning_Qwen3_32B_think": True,
    "smoltalk_smollm3_smol_magpie_ultra_no_think": False,
    "tulu_3_sft_personas_instruction_following_no_think": False,
    "hermes_function_calling_v1_no_think": False,
}
# FineVision configs (no ChartQA: it is the G2c eval set); modes alternate per row
VISION_SOURCES = {"CoSyn_400k_chart": True, "CoSyn_400k_document": False, "LLaVA_Instruct_150K": False,
                  "CoSyn_400k_diagram": True}
MAX_PROMPT_WORDS = 600


def pick_user_turn(row: dict) -> str | None:
    if isinstance(row.get("messages"), list):
        for m in row["messages"]:
            if m.get("role") == "user":
                text = m.get("content") if isinstance(m.get("content"), str) else None
                return text.strip() or None if text else None
        return None
    texts = row.get("texts")
    if isinstance(texts, list) and texts and isinstance(texts[0], dict):
        text = (texts[0].get("user") or "").strip()
        return text or None
    return None


def plan_jobs(sources: dict[str, bool], n: int) -> list[tuple[str, bool]]:
    """Round-robin over sources, n jobs total, each with its source's think mode."""
    return list(itertools.islice(itertools.cycle(sources.items()), n))


def _stream(dataset: str, config: str, split: str):
    from datasets import load_dataset
    return iter(load_dataset(dataset, config, split=split, streaming=True).shuffle(seed=7, buffer_size=200))


def text_prompts(n: int):
    streams = {s: _stream("HuggingFaceTB/smoltalk2", "SFT", s) for s in TEXT_SOURCES}
    for src, think in plan_jobs(TEXT_SOURCES, n):
        for row in streams[src]:
            p = pick_user_turn(row)
            if p and len(p.split()) <= MAX_PROMPT_WORDS:
                yield {"kind": "text", "src": src, "think": think, "prompt": p, "images": None}
                break


def vision_prompts(n: int, images_dir: Path):
    images_dir.mkdir(parents=True, exist_ok=True)
    streams = {c: _stream("HuggingFaceM4/FineVision", c, "train") for c in VISION_SOURCES}
    for i, (src, _) in enumerate(plan_jobs(VISION_SOURCES, n)):
        for row in streams[src]:
            p = pick_user_turn(row)
            imgs = row.get("images") or []
            if not p or len(imgs) != 1:
                continue
            img = imgs[0].convert("RGB")
            img.thumbnail((1024, 1024))
            path = images_dir / f"{text_hash(src + p)}.png"
            img.save(path)
            yield {"kind": "vision", "src": src, "think": i % 2 == 0, "prompt": p, "images": [str(path)]}
            break


def answer(job: dict, url: str, out: Path, lock: threading.Lock) -> bool:
    user = ([{"type": "image", "image": job["images"][0]}, {"type": "text", "text": job["prompt"]}]
            if job["images"] else job["prompt"])
    try:
        c = chat(url, [{"role": "user", "content": user}], think=job["think"],
                 max_tokens=6144 if job["think"] else 2048, temperature=0.6 if job["think"] else 0.7)[0]
    except Exception:
        return False
    content = c["content"].strip()
    if not content or c["finish"] != "stop" or (job["think"] and not c["reasoning"].strip()):
        return False
    row = make_sample(job["prompt"], content, think=c["reasoning"] if job["think"] else None,
                      source=f"replay-{job['kind']}", meta={"src": job["src"], "pid": text_hash(job["prompt"])},
                      images=job["images"])
    with lock:
        append_jsonl(out, row)
    return True


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--text-n", type=int, required=True)
    ap.add_argument("--vision-n", type=int, required=True)
    ap.add_argument("--base-url", default="http://127.0.0.1:19300")
    ap.add_argument("--slots", type=int, default=4)
    ap.add_argument("--out", type=Path, default=DATA / "replay.jsonl")
    ap.add_argument("--images-dir", type=Path, default=DATA / "images")
    args = ap.parse_args(argv)

    done = {r["meta"]["pid"] for r in read_jsonl(args.out)}
    jobs = [j for j in itertools.chain(text_prompts(args.text_n), vision_prompts(args.vision_n, args.images_dir))
            if text_hash(j["prompt"]) not in done]
    lock = threading.Lock()
    with ThreadPoolExecutor(args.slots) as pool:
        ok = sum(pool.map(lambda j: answer(j, args.base_url, args.out, lock), jobs))
    print(json.dumps({"jobs": len(jobs), "kept": ok, "skipped_done": len(done)}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
